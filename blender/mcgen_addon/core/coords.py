"""Система координат: мир Minecraft (x на восток, y вверх, z на юг; правая тройка) -> Blender (X восток, Y север, Z вверх).

    Blender = (x, -z, y)

Построитель сцены (render.scene.SceneBuilder, основной путь) кладёт чанки в АБСОЛЮТНЫЕ координаты мира: объект чанка (cx, cz) стоит в
(cx*16, −cz*16), высота — абсолютная y Minecraft (уровень моря 63 лежит на Z = 63). Запасной предпросмотр (fallback_preview) сдвигает сцену так,
что началом служит юго-западный нижний угол области (cx0*16, cz0*16); сдвиг хранится в свойствах коллекции: mcgen_cx0, mcgen_cz0, mcgen_min_y.
Всё, что аддон добавляет к блокам (маркеры построек), берёт начало по тому же правилу — см. ui/ops.py::MCGEN_OT_structure_markers.
"""


def mc_to_blender(x, y, z):
    """Точка мира (x, y, z) в системе Blender (без учёта сдвига начала области)."""
    return (x, -z, y)


def blender_to_mc(bx, by, bz):
    return (bx, bz, -by)


def chunk_origin_blender(cx, cz, cx0, cz0):
    """Позиция минимального угла чанка (cx, cz) относительно начала области (cx0, cz0) в Blender (X, Y)."""
    return ((cx - cx0) * 16, -((cz - cz0) * 16))
