def build():
    """Словарь для bpy.app.translations: контексты '*' (свойства, подписи) и 'Operator' (кнопки-операторы)."""
    ru = dict(RU)
    doc = P.tweaks_doc()
    for t in doc['tweaks']:
        ru[t['label']] = t['label_ru']
        ru[t['description']] = t['description_ru']
    for g in doc['groups']:
        ru[g['label']] = g['label_ru']
    d = {}
    for en, tr in ru.items():
        d[('*', en)] = tr
        d[('Operator', en)] = tr
    return {'ru_RU': d}


_registered = []


def register():
    try:
        bpy.app.translations.register(__package__.rsplit('.', 1)[0], build())
        _registered.append(True)
    except ValueError:                  # уже зарегистрировано (перезагрузка)
        bpy.app.translations.unregister(__package__.rsplit('.', 1)[0])
        bpy.app.translations.register(__package__.rsplit('.', 1)[0], build())
        _registered.append(True)


def unregister():
    if _registered:
        try:
            bpy.app.translations.unregister(__package__.rsplit('.', 1)[0])
        except (ValueError, KeyError):
            pass
        _registered.clear()
